/// Look up the bitmap for a character. Returns `None` for non-ASCII / out-of-range.
#[inline]
fn glyph_bitmap(ch: char) -> Option<&'static [u8; 16]> {
    let code = ch as u32;
    if (32..=126).contains(&code) {
        Some(&FONT_8X16[(code - 32) as usize])
    } else {
        None
    }
}

// ---------------------------------------------------------------------------
// GlyphAtlas  (char, fg_rgb) → pre-rendered BGRA tile
// ---------------------------------------------------------------------------

/// Key for the atlas cache: character + foreground colour.
#[derive(Hash, Eq, PartialEq, Clone, Copy)]
struct GlyphKey {
    ch: char,
    fg: u32,
}

/// A single pre-rendered glyph tile in BGRA byte order.
struct GlyphTile {
    /// BGRA pixels, row-major, `GLYPH_W * GLYPH_H * 4` bytes.
    data: Vec<u8>,
}

pub struct GlyphAtlas {
    cache: HashMap<GlyphKey, GlyphTile>,
}

impl GlyphAtlas {
    pub fn new() -> Self {
        Self {
            cache: HashMap::with_capacity(256),
        }
    }

    /// Get or render a glyph tile for `(ch, fg)` in **BGRA** byte order.
    fn get_or_render(&mut self, ch: char, fg: u32) -> &[u8] {
        let key = GlyphKey { ch, fg };
        self.cache.entry(key).or_insert_with(|| {
            let mut data = vec![0u8; (GLYPH_W * GLYPH_H * 4) as usize];
            if let Some(bitmap) = glyph_bitmap(ch) {
                let r = ((fg >> 16) & 0xFF) as u8;
                let g = ((fg >> 8) & 0xFF) as u8;
                let b = (fg & 0xFF) as u8;
                for row in 0..GLYPH_H as usize {
                    let bits = bitmap[row];
                    for col in 0..GLYPH_W as usize {
                        if bits & (0x80 >> col) != 0 {
                            let idx = (row * GLYPH_W as usize + col) * 4;
                            // BGRA order for gpui
                            data[idx] = b;
                            data[idx + 1] = g;
                            data[idx + 2] = r;
                            data[idx + 3] = 0xFF;
                        }
                    }
                }
            }
            GlyphTile { data }
        });
        &self.cache[&key].data
    }

    /// Clear the entire cache (e.g. on font / colour-scheme change).
    #[allow(dead_code)]
    pub fn clear(&mut self) {
        self.cache.clear();
    }
}

