// GridRenderer
// ---------------------------------------------------------------------------

pub struct GridRenderer {
    atlas: GlyphAtlas,
    /// BGRA pixel buffer (buf_width × buf_height × 4 bytes)
    pixel_buf: Vec<u8>,
    buf_width: u32,
    buf_height: u32,
    cell_width: u32,
    cell_height: u32,
    cols: u32,
    rows: u32,
    dirty: bool,
    cached_image: Option<Arc<RenderImage>>,
}

impl GridRenderer {
    /// Create a new grid renderer for `cols × rows` cells.
    pub fn new(cols: u32, rows: u32) -> Self {
        let cell_width = GLYPH_W;
        let cell_height = GLYPH_H;
        let buf_width = cols * cell_width;
        let buf_height = rows * cell_height;
        let buf_size = (buf_width * buf_height * 4) as usize;
        Self {
            atlas: GlyphAtlas::new(),
            pixel_buf: vec![0u8; buf_size],
            buf_width,
            buf_height,
            cell_width,
            cell_height,
            cols,
            rows,
            dirty: true,
            cached_image: None,
        }
    }

    /// Bulk-update the entire grid from a 2D cell array (rows × cols).
    pub fn update_cells(&mut self, cells: &[Vec<GridCell>]) {
        for (r, row) in cells.iter().enumerate() {
            let r = r as u32;
            if r >= self.rows {
                break;
            }
            for (c, cell) in row.iter().enumerate() {
                let c = c as u32;
                if c >= self.cols {
                    break;
                }
                self.paint_cell(r, c, *cell);
            }
        }
        self.dirty = true;
    }

    /// Update a single cell and mark dirty.
    pub fn update_cell(&mut self, row: u32, col: u32, cell: GridCell) {
        if row < self.rows && col < self.cols {
            self.paint_cell(row, col, cell);
            self.dirty = true;
        }
    }

    /// Produce a `RenderImage` suitable for `gpui::img()`.
    /// Re-renders only when dirty; otherwise returns a cached `Arc`.
    pub fn render_image(&mut self) -> Arc<RenderImage> {
        if !self.dirty {
            if let Some(ref cached) = self.cached_image {
                return cached.clone();
            }
        }

        // The image crate's ImageBuffer<Rgba<u8>> expects RGBA byte order,
        // but gpui's sprite atlas reads the raw bytes as BGRA.
        // We store BGRA in pixel_buf, so we pass the raw bytes directly.
        let buf = ImageBuffer::<Rgba<u8>, _>::from_raw(
            self.buf_width,
            self.buf_height,
            self.pixel_buf.clone(),
        )
        .expect("pixel_buf size matches buf_width * buf_height * 4");

        let frame = image::Frame::new(buf);
        let render_image = Arc::new(RenderImage::new(smallvec![frame]));

        self.cached_image = Some(render_image.clone());
        self.dirty = false;
        render_image
    }

    /// Resize the grid (re-allocates the pixel buffer).
    pub fn resize(&mut self, cols: u32, rows: u32) {
        if cols == self.cols && rows == self.rows {
            return;
        }
        self.cols = cols;
        self.rows = rows;
        self.buf_width = cols * self.cell_width;
        self.buf_height = rows * self.cell_height;
        let buf_size = (self.buf_width * self.buf_height * 4) as usize;
        self.pixel_buf = vec![0u8; buf_size];
        self.dirty = true;
        self.cached_image = None;
    }

    /// Returns `(cell_width, cell_height)` in pixels.
    pub fn cell_size(&self) -> (u32, u32) {
        (self.cell_width, self.cell_height)
    }

    /// Returns `(cols, rows)`.
    pub fn grid_size(&self) -> (u32, u32) {
        (self.cols, self.rows)
    }

    /// Returns `(buf_width, buf_height)` in pixels.
    pub fn pixel_size(&self) -> (u32, u32) {
        (self.buf_width, self.buf_height)
    }

    // -- private helpers ---------------------------------------------------

    /// Paint a single cell into the pixel buffer (bg fill + glyph blit).
    fn paint_cell(&mut self, row: u32, col: u32, cell: GridCell) {
        let x0 = (col * self.cell_width) as usize;
        let y0 = (row * self.cell_height) as usize;
        let stride = (self.buf_width * 4) as usize;

        // Extract BGRA components for background
        let bg_b = (cell.bg & 0xFF) as u8;
        let bg_g = ((cell.bg >> 8) & 0xFF) as u8;
        let bg_r = ((cell.bg >> 16) & 0xFF) as u8;

        // 1. Fill background
        for dy in 0..self.cell_height as usize {
            let row_start = (y0 + dy) * stride + x0 * 4;
            for dx in 0..self.cell_width as usize {
                let idx = row_start + dx * 4;
                self.pixel_buf[idx] = bg_b;
                self.pixel_buf[idx + 1] = bg_g;
                self.pixel_buf[idx + 2] = bg_r;
                self.pixel_buf[idx + 3] = 0xFF;
            }
        }

        // 2. Blit glyph (skip space — already have bg)
        if cell.ch != ' ' {
            let glyph = self.atlas.get_or_render(cell.ch, cell.fg);
            for dy in 0..self.cell_height as usize {
                let dst_start = (y0 + dy) * stride + x0 * 4;
                let src_start = dy * self.cell_width as usize * 4;
                for dx in 0..self.cell_width as usize {
                    let si = src_start + dx * 4;
                    if glyph[si + 3] != 0 {
                        // opaque foreground pixel
                        let di = dst_start + dx * 4;
                        self.pixel_buf[di] = glyph[si];
                        self.pixel_buf[di + 1] = glyph[si + 1];
                        self.pixel_buf[di + 2] = glyph[si + 2];
                        self.pixel_buf[di + 3] = 0xFF;
                    }
                }
            }
        }

        // 3. Underline (flag bit 2)
        if cell.flags & 0x04 != 0 {
            let fg_b = (cell.fg & 0xFF) as u8;
            let fg_g = ((cell.fg >> 8) & 0xFF) as u8;
            let fg_r = ((cell.fg >> 16) & 0xFF) as u8;
            // Draw underline on the last row of the cell
            let ul_y = y0 + self.cell_height as usize - 1;
            let row_start = ul_y * stride + x0 * 4;
            for dx in 0..self.cell_width as usize {
                let idx = row_start + dx * 4;
                self.pixel_buf[idx] = fg_b;
                self.pixel_buf[idx + 1] = fg_g;
                self.pixel_buf[idx + 2] = fg_r;
                self.pixel_buf[idx + 3] = 0xFF;
            }
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn default_cell() {
        let c = GridCell::default();
        assert_eq!(c.ch, ' ');
        assert_eq!(c.fg, 0xE5E5E5);
        assert_eq!(c.bg, 0x1E1E1E);
        assert_eq!(c.flags, 0);
    }

    #[test]
    fn glyph_lookup_ascii() {
        assert!(glyph_bitmap(' ').is_some());
        assert!(glyph_bitmap('A').is_some());
        assert!(glyph_bitmap('~').is_some());
        assert!(glyph_bitmap('\x1f').is_none()); // below range
        assert!(glyph_bitmap('\x7f').is_none()); // above range
    }

    #[test]
    fn renderer_creates_image() {
        let mut r = GridRenderer::new(80, 24);
        let img = r.render_image();
        // Image should have correct pixel dimensions
        let size = img.size(0);
        assert_eq!(size.width.0, (80 * 8) as i32);
        assert_eq!(size.height.0, (24 * 16) as i32);
    }

    #[test]
    fn renderer_caches() {
        let mut r = GridRenderer::new(10, 5);
        let a = r.render_image();
        let b = r.render_image();
        // Same Arc (same ImageId) when not dirty
        assert_eq!(a.id, b.id);
    }

    #[test]
    fn update_cell_marks_dirty() {
        let mut r = GridRenderer::new(10, 5);
        let _ = r.render_image(); // clear dirty
        r.update_cell(0, 0, GridCell { ch: 'X', ..Default::default() });
        // After update, a new render should produce a new image
        let img = r.render_image();
        assert_eq!(img.size(0).width.0, (10 * 8) as i32);
    }

    #[test]
    fn resize_works() {
        let mut r = GridRenderer::new(80, 24);
        r.resize(120, 40);
        assert_eq!(r.grid_size(), (120, 40));
        assert_eq!(r.pixel_size(), (120 * 8, 40 * 16));
    }
}
