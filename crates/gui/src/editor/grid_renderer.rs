/// A single cell in the terminal/editor grid.
#[derive(Clone, Copy, Debug)]
pub struct GridCell {
    /// Unicode codepoint to display
    pub ch: char,
    /// RGB foreground colour (0xRRGGBB)
    pub fg: u32,
    /// RGB background colour (0xRRGGBB)
    pub bg: u32,
    /// Flags — bit 0 = bold, bit 1 = italic, bit 2 = underline
    pub flags: u8,
}

impl Default for GridCell {
    fn default() -> Self {
        Self {
            ch: ' ',
            fg: 0xE5E5E5,
            bg: 0x1E1E1E,
            flags: 0,
        }
    }
}

